create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  uid bigint generated by default as identity unique,
  username text not null unique check (username ~ '^[a-z0-9_]{3,32}$'),
  display_name text not null default '' check (char_length(display_name) <= 64),
  bio text not null default '' check (char_length(bio) <= 280),
  status_emoji text not null default '' check (char_length(status_emoji) <= 16),
  status_text text not null default '' check (char_length(status_text) <= 80),
  avatar_url text,
  avatar_animated boolean not null default false,
  profile_bg text check (profile_bg is null or profile_bg ~ '^#[0-9a-fA-F]{6}$'),
  music_url text,
  music_title text not null default '' check (char_length(music_title) <= 80),
  public_key text check (public_key is null or char_length(public_key) <= 200),
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table public.chats (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('direct','group','channel')),
  title text not null default '' check (char_length(title) <= 64),
  description text not null default '' check (char_length(description) <= 280),
  avatar_url text,
  avatar_animated boolean not null default false,
  direct_key text unique,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.chat_members (
  chat_id uuid not null references public.chats(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','member')),
  pinned boolean not null default false,
  muted boolean not null default false,
  last_read_at timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  primary key (chat_id, user_id)
);

alter table public.chat_members add constraint chat_members_user_profile_fkey foreign key (user_id) references public.profiles(id) on delete cascade;

create table public.sticker_packs (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 64),
  short_name text not null unique check (short_name ~ '^[a-z0-9_]{3,40}$'),
  created_at timestamptz not null default now()
);

create table public.stickers (
  id uuid primary key default gen_random_uuid(),
  pack_id uuid not null references public.sticker_packs(id) on delete cascade,
  url text not null,
  animated boolean not null default false,
  emoji text not null default '' check (char_length(emoji) <= 16),
  created_at timestamptz not null default now()
